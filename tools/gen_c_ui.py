def outputs(root):
    schema=json.loads((root/'runtime/dunit-c/api.json').read_text())
    if set(schema)!={'constants','callbacks','records','functions'}:raise ValueError('unknown C UI API section')
    # gui-v1 owns its input kind values; the C observer never copies them.
    control=(root/'protocols/gui-v1/src/control.rs').read_text()
    inputs=re.findall(r'^pub const (IN_\w+): u8 = (\d+);',control,re.M)
    if not inputs:raise ValueError('missing gui-v1 input kinds')
    schema['constants'].update(('DUNIT_GUI_'+name,int(value))for name,value in inputs)
    transfer=(root/'protocols/gui-v1/src/transfer.rs').read_text()
    file_kind=re.search(r'pub enum FileKind \{(.*?)\n\}',transfer,re.S)
    if file_kind is None:raise ValueError('missing transfer FileKind')
    kinds=re.findall(r'(\w+)\s*=\s*(\d+)',file_kind.group(1))
    if not kinds:raise ValueError('missing transfer file kind values')
    schema['constants'].update(('DUNIT_TRANSFER_FILE_KIND_'+name.upper(),int(value))for name,value in kinds)
    types=dict(TYPES)
    for name in schema['callbacks']:types[name]=(name,f'Option<{name}>')
    def ident(name):
        if not re.fullmatch(r'[A-Za-z_]\w*',name):raise ValueError('invalid API identifier')
        return name
    def signature(value,language,names=False):
        return ', '.join(types[kind][language]+(' '+ident(name) if names else '') for name,kind in value['args'])
    notice='GENERATED by tools/gen_abi.py from runtime/dunit-c/api.json; do not edit.'
    c=['/* '+notice+' */','#ifndef DUNIT_UI_H','#define DUNIT_UI_H','#include <stdint.h>','#include <stddef.h>','']
    rust=['// '+notice]
    for name,value in schema['constants'].items():
        ident(name)
        if type(value)is not int or not 0<=value<=0xffffffff:raise ValueError('invalid UI constant')
        c.append(f'#define {name} {value}u');rust.append(f'pub const {name}:u32={value};')
    for name in schema['records']:c.append(f'struct {ident(name)};')
    for name,value in schema['callbacks'].items():
        c.append(f'typedef {types[value["result"]][0]} (*{ident(name)})({signature(value,0,True)});')
        rust.append(f'pub type {name}=unsafe extern "C" fn({signature(value,1)})->{types[value["result"]][1]};')
    for name,record in schema['records'].items():
        c.append(f'typedef struct {ident(name)} {{')
        rust.extend(['#[repr(C)]','#[derive(Clone,Copy)]',f'pub struct {name} {{'])
        for field,kind in record['fields']:
            c.append(f'    {types[kind][0]} {ident(field)};')
            rust.append(f'    pub {field}:{types[kind][1]},')
        c.append(f'}} {name};');rust.append('}')
        rust.extend([f'const _: [();{record["size"]}]=[();core::mem::size_of::<{name}>()];',f'const _: [();{record["align"]}]=[();core::mem::align_of::<{name}>()];'])
    c.extend(['','#ifdef __cplusplus','extern "C" {','#endif'])
    for name,value in schema['functions'].items():
        c.append(f'{types[value["result"]][0]} {ident(name)}({signature(value,0,True)});')
        rust.append(f'const _:unsafe extern "C" fn({signature(value,1)})->{types[value["result"]][1]}=crate::{name};')
    c.extend(['#ifdef __cplusplus','}','#endif','#endif /* DUNIT_UI_H */',''])
    return [(root/'abi/include/dunit/ui.h','\n'.join(c)),(root/'runtime/dunit-c/src/generated.rs','\n'.join(rust)+'\n')]
