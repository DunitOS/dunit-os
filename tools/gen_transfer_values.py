"""Render transfer/file capability values as part of tools/gen_abi.py."""
import json
import tomllib

def outputs(root,screaming):
    source=root/'abi/transfers.abi';data=tomllib.loads(source.read_text())
    schema={'Kind':('Kind','u16','from_u16','DUNIT_TRANSFER_KIND'),
        'Action':('Action','u32','from_u32','DUNIT_TRANSFER_ACTION'),
        'Status':('Status','u32','from_u32','DUNIT_TRANSFER_STATUS'),
        'FileOperation':('Operation','u64','from_raw','DUNIT_FILE_OP'),
        'FileRelation':('Relation','u32','from_raw','DUNIT_FILE_RELATION')}
    if set(data)!=set(schema)|{'Mime'}:raise ValueError('Unexpected transfer ABI sections')
    notice='GENERATED by tools/gen_abi.py from abi/transfers.abi; do not edit.'
    rust=[];files=[];headers=['/* '+notice+' */','#ifndef DUNIT_TRANSFER_H','#define DUNIT_TRANSFER_H','']
    for section,(name,integer,method,prefix) in schema.items():
        entries=data[section]
        if not entries or len(set(entries.values()))!=len(entries):raise ValueError('Empty or duplicate values in '+section)
        if any(type(value)is not int or not 0<=value<(1<<int(integer[1:])) for value in entries.values()):raise ValueError('Invalid values in '+section)
        block=[f'#[repr({integer})]','#[derive(Debug,Clone,Copy,PartialEq,Eq)]',f'pub enum {name} {{']
        block += [f'    {key} = {value},' for key,value in entries.items()]
        block += ['}',f'impl {name} {{',f'    pub const fn {method}(value:{integer})->Option<Self>{{', '        Some(match value {']
        block += [f'            {value}=>Self::{key},' for key,value in entries.items()]
        block += ['            _=>return None,','        })','    }','}']
        (files if section.startswith('File') else rust).extend(block+[''])
        headers += [f'#define {prefix}_{screaming(key)} {value}u' for key,value in entries.items()]+['']
    for key,value in data['Mime'].items():
        if not isinstance(value,str) or not value.isascii() or any(ord(ch)<32 for ch in value):raise ValueError('Invalid MIME constant')
        rust.append(f'pub const {key}:&str={json.dumps(value)};')
        headers.append(f'#define DUNIT_TRANSFER_{key} {json.dumps(value)}')
    headers += ['','#endif /* DUNIT_TRANSFER_H */','']
    return [(root/'protocols/gui-v1/src/transfer/values.rs','// '+notice+'\n'+'\n'.join(rust)+'\n'),
        (root/'abi/file-cap/src/generated.rs','// '+notice+'\n'+'\n'.join(files)),
        (root/'abi/include/dunit/transfer.h','\n'.join(headers))]
