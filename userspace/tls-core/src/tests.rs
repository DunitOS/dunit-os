#[test]
fn rfc7748_x25519_vectors() {
    // RFC 7748 Section 5.2 Alice & Bob shared secret test vector.
    let alice_priv: [u8; 32] = [
        0x77, 0x07, 0x6d, 0x0a, 0x73, 0x18, 0xa5, 0x7d, 0x3c, 0x16, 0xc1, 0x72, 0x51, 0xb2, 0x66,
        0x45, 0xdf, 0x4c, 0x2f, 0x87, 0xeb, 0xc0, 0x99, 0x2a, 0xb1, 0x77, 0xfb, 0xa5, 0x1d, 0xb9,
        0x2c, 0x2a,
    ];
    let bob_pub: [u8; 32] = [
        0xde, 0x9e, 0xdb, 0x7d, 0x7b, 0x7d, 0xc1, 0xb4, 0xd3, 0x5b, 0x61, 0xc2, 0xec, 0xe4, 0x35,
        0x37, 0x3f, 0x83, 0x43, 0xc8, 0x5b, 0x78, 0x67, 0x4d, 0xad, 0xfc, 0x7e, 0x14, 0x6f, 0x88,
        0x2b, 0x4f,
    ];
    let expected_alice_pub: [u8; 32] = [
        0x85, 0x20, 0xf0, 0x09, 0x89, 0x30, 0xa7, 0x54, 0x74, 0x8b, 0x7d, 0xdc, 0xb4, 0x3e, 0xf7,
        0x5a, 0x0d, 0xbf, 0x3a, 0x0d, 0x26, 0x38, 0x1a, 0xf4, 0xeb, 0xa4, 0xa9, 0x8e, 0xaa, 0x9b,
        0x4e, 0x6a,
    ];
    let expected_shared: [u8; 32] = [
        0x4a, 0x5d, 0x9d, 0x5b, 0xa4, 0xce, 0x2d, 0xe1, 0x72, 0x8e, 0x3b, 0xf4, 0x80, 0x35, 0x0f,
        0x25, 0xe0, 0x7e, 0x21, 0xc9, 0x47, 0xd1, 0x9e, 0x33, 0x76, 0xf0, 0x9b, 0x3c, 0x1e, 0x16,
        0x17, 0x42,
    ];
    assert_eq!(x25519::x25519_base(&alice_priv), expected_alice_pub);
    assert_eq!(x25519::x25519(&alice_priv, &bob_pub), expected_shared);
}

#[test]
fn rfc8439_chacha20_poly1305_vector() {
    let key: [u8; 32] = [
        0x80, 0x81, 0x82, 0x83, 0x84, 0x85, 0x86, 0x87, 0x88, 0x89, 0x8a, 0x8b, 0x8c, 0x8d, 0x8e,
        0x8f, 0x90, 0x91, 0x92, 0x93, 0x94, 0x95, 0x96, 0x97, 0x98, 0x99, 0x9a, 0x9b, 0x9c, 0x9d,
        0x9e, 0x9f,
    ];
    let nonce: [u8; 12] = [0x07, 0x00, 0x00, 0x00, 0x40, 0x41, 0x42, 0x43, 0x44, 0x45, 0x46, 0x47];
    let aad = [0x50, 0x51, 0x52, 0x53, 0xc0, 0xc1, 0xc2, 0xc3, 0xc4, 0xc5, 0xc6, 0xc7];
    let pt = b"Ladies and Gentlemen of the class of '99: If I could offer you only one tip for the future, sunscreen would be it.";
    let out = chacha20_poly1305_seal(&key, &nonce, &aad, pt);
    assert_eq!(out.len(), pt.len() + 16);
    assert_eq!(
        &out[out.len() - 16..],
        &[0x1a, 0xe1, 0x0b, 0x59, 0x4f, 0x09, 0xe2, 0x6a, 0x7e, 0x90, 0x2e, 0xcb, 0xd0, 0x60, 0x06, 0x91]
    );
    assert_eq!(chacha20_poly1305_open(&key, &nonce, &aad, &out).unwrap(), pt);
    let mut tampered = out.clone();
    tampered[0] ^= 1;
    assert_eq!(chacha20_poly1305_open(&key, &nonce, &aad, &tampered), None);
}

#[test]
fn nist_aes128_gcm_and_hkdf_vectors() {
    // NIST SP 800-38D Test Case 4: 16-byte key, 12-byte IV, 60-byte PT, 20-byte AAD.
    let key: [u8; 16] = [
        0xfe, 0xff, 0xe9, 0x92, 0x86, 0x65, 0x73, 0x1c, 0x6d, 0x6a, 0x8f, 0x94, 0x67, 0x30, 0x83,
        0x08,
    ];
    let iv: [u8; 12] = [0xca, 0xfe, 0xba, 0xbe, 0xfa, 0xce, 0xdb, 0xad, 0xde, 0xca, 0xf8, 0x88];
    let pt: [u8; 60] = [
        0xd9, 0x31, 0x32, 0x25, 0xf8, 0x84, 0x06, 0xe5, 0xa5, 0x59, 0x09, 0xc5, 0xaf, 0xf5, 0x26,
        0x9a, 0x86, 0xa7, 0xa9, 0x53, 0x15, 0x34, 0xf7, 0xda, 0x2e, 0x4c, 0x30, 0x3d, 0x8a, 0x31,
        0x8a, 0x72, 0x1c, 0x3c, 0x0c, 0x95, 0x95, 0x68, 0x09, 0x53, 0x2f, 0xcf, 0x0e, 0x24, 0x49,
        0xa6, 0xb5, 0x25, 0xb1, 0x6a, 0xed, 0xf5, 0xaa, 0x0d, 0xe6, 0x57, 0xba, 0x63, 0x7b, 0x39,
    ];
    let aad: [u8; 20] = [
        0xfe, 0xed, 0xfa, 0xce, 0xde, 0xad, 0xbe, 0xef, 0xfe, 0xed, 0xfa, 0xce, 0xde, 0xad, 0xbe,
        0xef, 0xab, 0xad, 0xda, 0xd2,
    ];
    let sealed = aes128_gcm_seal(&key, &iv, &aad, &pt);
    assert_eq!(
        &sealed[60..],
        &[0x5b, 0xc9, 0x4f, 0xbc, 0x32, 0x21, 0xa5, 0xdb, 0x94, 0xfa, 0xe9, 0x5a, 0xe7, 0x12, 0x1a, 0x47]
    );
    assert_eq!(aes128_gcm_open(&key, &iv, &aad, &sealed).unwrap(), pt);

    // SHA-256 of empty input (RFC 8448).
    assert_eq!(
        sha256(&[]),
        [
            0xe3, 0xb0, 0xc4, 0x42, 0x98, 0xfc, 0x1c, 0x14, 0x9a, 0xfb, 0xf4, 0xc8, 0x99, 0x6f, 0xb9,
            0x24, 0x27, 0xae, 0x41, 0xe4, 0x64, 0x9b, 0x93, 0x4c, 0xa4, 0x95, 0x99, 0x1b, 0x78, 0x52,
            0xb8, 0x55,
        ]
    );
}

#[test]
fn p256_ecdsa_vector() {
    // Generated with OpenSSL prime256v1 + SHA256("sample").
    let q_sec1: [u8; 65] = [
        0x04, 0x2e, 0x45, 0x53, 0x33, 0x71, 0x99, 0x39, 0xc7, 0x94, 0x72, 0x3d, 0xae, 0x14, 0x3c,
        0xbd, 0x12, 0xdb, 0x4a, 0x47, 0x00, 0x98, 0x93, 0xce, 0x58, 0xd6, 0xac, 0x16, 0x2e, 0x12,
        0x13, 0x80, 0x2c, 0x7d, 0xca, 0x28, 0xb3, 0x5d, 0x70, 0x5a, 0xf8, 0x53, 0x15, 0xb2, 0x41,
        0x0a, 0xa4, 0x7a, 0xd2, 0x49, 0x65, 0x58, 0xc1, 0x65, 0x0d, 0x0b, 0x5b, 0xbb, 0x11, 0x32,
        0x84, 0x10, 0x03, 0x30, 0xce,
    ];
    let sig_der: &[u8] = &[
        0x30, 0x44, 0x02, 0x20, 0x12, 0x7b, 0x3c, 0x84, 0x6a, 0xf1, 0x4e, 0xe8, 0xc6, 0xac, 0xe8,
        0xc4, 0x39, 0x53, 0x9f, 0xfa, 0x6b, 0xda, 0x79, 0x99, 0xe3, 0x77, 0x98, 0xb6, 0xb2, 0x25,
        0xe7, 0xa0, 0x57, 0x21, 0xff, 0x13, 0x02, 0x20, 0x08, 0x75, 0x54, 0xcb, 0x1b, 0x9e, 0xe1,
        0xe5, 0x6e, 0x2b, 0xde, 0x6a, 0x53, 0x5d, 0x13, 0xee, 0xcd, 0x8f, 0x2d, 0x1f, 0x1d, 0xdd,
        0xc6, 0xfa, 0x96, 0x5f, 0x14, 0x0f, 0xb8, 0xe9, 0x1f, 0x2e,
    ];
    let (r, s) = x509::parse_ecdsa_sig_der(sig_der).unwrap();
    let digest = sha256(b"sample");
    assert_eq!(ecdsa_p256::debug_self_check(), Ok(()));
    assert_eq!(ecdsa_p256::verify_p256_step(&q_sec1, &digest, r, s), Ok(()));
    assert!(ecdsa_p256::verify_p256_sha256(&q_sec1, &digest, r, s));
    let mut bad_r = r.to_vec();
    bad_r[0] ^= 0xff;
    assert!(!ecdsa_p256::verify_p256_sha256(&q_sec1, &digest, &bad_r, s));
}
